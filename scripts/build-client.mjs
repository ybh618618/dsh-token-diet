import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const pkgDir = join(root, 'packages', 'token-diet')
const parts = ['01-util.js', '02-page.js', '03-composer.js', '04-main.js']

const bodies = []
for (const part of parts) {
  const text = await readFile(join(pkgDir, 'src', 'client', part), 'utf8')
  bodies.push(`    // ---- src/client/${part} ----\n${text.replace(/\s+$/, '')}\n`)
}

const banner = `/* Generated by scripts/build-client.mjs — edit src/client/*.js instead. */
window.__ModuleLoader__.load({
  id: 'dsh-token-diet',
  factory(require) {
    const React = require('react')
    const h = React.createElement
    const TD = {}
`

const footer = `
    // The render harness reaches the shared namespace through this handle; the
    // loader only reads \`apply\`/\`inject\`, so exposing it is inert at runtime.
    return { inject: TD.inject, apply: TD.apply, __TD: TD }
  },
})
`

await writeFile(join(pkgDir, 'lib', 'client.js'), banner + bodies.join('\n') + footer)
console.log(`built packages/token-diet/lib/client.js from ${parts.length} parts`)
